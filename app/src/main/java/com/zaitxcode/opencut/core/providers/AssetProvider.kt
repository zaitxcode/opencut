package com.zaitxcode.opencut.core.providers

import android.content.Context
import com.zaitxcode.opencut.core.render.LutFactory
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json
import java.io.File
import java.net.HttpURLConnection
import java.net.URL

/** The kinds of downloadable content a provider can offer. */
@Serializable
enum class AssetKind {
    FILTER,
    EFFECT,
    STICKER,
    TRANSITION,
    FONT,
    SOUND,
    TEMPLATE,
}

/**
 * One downloadable item.
 *
 * [license] is mandatory on purpose: a provider must state the terms of every
 * asset it serves so the editor can refuse to show content whose licence is not
 * known to be redistributable.
 */
@Serializable
data class RemoteAsset(
    val id: String,
    val name: String,
    val kind: AssetKind,
    val url: String = "",
    val previewUrl: String = "",
    val bytes: Long = 0L,
    val license: String = "",
    val author: String = "",
) {
    val isRedistributable: Boolean
        get() = license.isNotBlank()
}

/** Thrown when a provider is asked for content it cannot serve. */
class AssetProviderException(message: String) : Exception(message)

/**
 * Source of extra content for the editor.
 *
 * OpenCut ships with a complete offline catalogue and works with no provider at
 * all. A provider only adds *more* content.
 *
 * The interface is intentionally transport agnostic. The bundled implementation
 * is [LocalAssetProvider]; [HttpAssetProvider] is provided for people who want to
 * host their own catalogue of original or properly licensed assets.
 *
 * It is not wired to any commercial service. The endpoints of a proprietary
 * service may not be called by a third-party client, and their effects, filters
 * and stickers are artwork that cannot be redistributed in an open-source
 * project.
 */
interface AssetProvider {

    /** Stable identifier, shown in settings. */
    val id: String

    /** Human readable name. */
    val displayName: String

    /** True when the provider can work without a network connection. */
    val worksOffline: Boolean

    /** Lists the content the provider offers. */
    suspend fun catalogue(): List<RemoteAsset>

    /**
     * Downloads [asset] into [destination].
     *
     * Implementations must validate the payload (size and checksum when known)
     * before returning.
     */
    suspend fun download(asset: RemoteAsset, destination: File): File
}

/**
 * The content that ships inside the app.
 *
 * The looks are generated analytically by [LutFactory] rather than shipped as
 * binary cube files, so this provider is genuinely offline and adds no assets to
 * the APK.
 */
class LocalAssetProvider : AssetProvider {

    override val id: String = "local"
    override val displayName: String = "Built-in"
    override val worksOffline: Boolean = true

    override suspend fun catalogue(): List<RemoteAsset> =
        LutFactory.catalogue().map { (look, label) ->
            RemoteAsset(
                id = "lut.${look.name.lowercase()}",
                name = label,
                kind = AssetKind.FILTER,
                license = "Generated by OpenCut (MIT)",
                author = "OpenCut",
            )
        } + builtInEffects

    override suspend fun download(asset: RemoteAsset, destination: File): File {
        // Built-in content is generated at runtime, so there is nothing to fetch.
        throw AssetProviderException("${asset.name} is built in and needs no download")
    }

    private val builtInEffects = listOf(
        RemoteAsset(id = "effect.brighten", name = "Brighten", kind = AssetKind.EFFECT, license = "MIT", author = "OpenCut"),
        RemoteAsset(id = "effect.punch", name = "Punch", kind = AssetKind.EFFECT, license = "MIT", author = "OpenCut"),
        RemoteAsset(id = "effect.soft", name = "Soft", kind = AssetKind.EFFECT, license = "MIT", author = "OpenCut"),
        RemoteAsset(id = "effect.vignette", name = "Vignette", kind = AssetKind.EFFECT, license = "MIT", author = "OpenCut"),
        RemoteAsset(id = "effect.grain", name = "Grain", kind = AssetKind.EFFECT, license = "MIT", author = "OpenCut"),
        RemoteAsset(id = "transition.fade", name = "Fade", kind = AssetKind.TRANSITION, license = "MIT", author = "OpenCut"),
    )
}

/**
 * Reads a catalogue from a plain HTTP(S) endpoint that the operator controls.
 *
 * The catalogue is a JSON array of [RemoteAsset]. Nothing is hard coded: the base
 * URL is supplied by the caller, so this class contains no reference to any
 * third party service.
 */
class HttpAssetProvider(
    private val baseUrl: String,
    override val displayName: String = "Custom catalogue",
) : AssetProvider {

    override val id: String = "http:$baseUrl"
    override val worksOffline: Boolean = false

    private val json = Json { ignoreUnknownKeys = true }

    override suspend fun catalogue(): List<RemoteAsset> {
        val payload = read("$baseUrl/catalogue.json")
        val assets = runCatching {
            json.decodeFromString(kotlinx.serialization.builtins.ListSerializer(RemoteAsset.serializer()), payload)
        }.getOrElse { throw AssetProviderException("Malformed catalogue: ${it.message}") }
        // Refuse content whose licence is unknown: an open-source editor must not
        // become a distribution channel for unlicensed artwork.
        return assets.filter { it.isRedistributable }
    }

    override suspend fun download(asset: RemoteAsset, destination: File): File {
        if (!asset.isRedistributable) {
            throw AssetProviderException("${asset.name} has no declared licence")
        }
        val bytes = read(asset.url).toByteArray()
        if (asset.bytes > 0 && bytes.size.toLong() != asset.bytes) {
            throw AssetProviderException("Size mismatch for ${asset.name}")
        }
        destination.parentFile?.mkdirs()
        destination.writeBytes(bytes)
        return destination
    }

    private fun read(url: String): String {
        val connection = URL(url).openConnection() as HttpURLConnection
        connection.connectTimeout = 15_000
        connection.readTimeout = 30_000
        connection.requestMethod = "GET"
        return try {
            if (connection.responseCode !in 200..299) {
                throw AssetProviderException("HTTP ${connection.responseCode} for $url")
            }
            connection.inputStream.bufferedReader().use { it.readText() }
        } finally {
            connection.disconnect()
        }
    }
}

/**
 * Keeps the active provider.
 *
 * The default is the offline provider; the editor never needs anything else.
 */
object AssetProviders {

    @Volatile
    private var active: AssetProvider = LocalAssetProvider()

    fun current(): AssetProvider = active

    fun use(provider: AssetProvider) {
        active = provider
    }

    fun reset() {
        active = LocalAssetProvider()
    }

    /** Providers available in a stock build. */
    fun builtIn(): List<AssetProvider> = listOf(LocalAssetProvider())

    /**
     * Creates a provider for a catalogue the user hosts themselves.
     *
     * Kept separate from [builtIn] so the default build makes no network calls.
     */
    fun custom(baseUrl: String, name: String = "Custom catalogue"): AssetProvider =
        HttpAssetProvider(baseUrl.trimEnd('/'), name)
}
